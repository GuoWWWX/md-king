import { createRequire } from "node:module";
import { readFile } from "node:fs/promises";

// Vite already supplies esbuild; bundle the installed engine for offline export.
const { build } = createRequire(import.meta.resolve("vite"))("esbuild");
const { version } = JSON.parse(await readFile(new URL("../node_modules/mermaid/package.json", import.meta.url), "utf8"));
await build({
  // The prebundled entry embeds its own DOMPurify; core uses our patched dependency.
  entryPoints: ["node_modules/mermaid/dist/mermaid.core.mjs"],
  outfile: "src-tauri/resources/mermaid/mermaid.min.js",
  bundle: true,
  minify: true,
  format: "iife",
  globalName: "mdKingMermaid",
  platform: "browser",
  target: "es2024",
  banner: { js: `// Mermaid ${version}; generated by scripts/bundle-mermaid.mjs.` },
  footer: { js: "globalThis.mermaid = mdKingMermaid.default;" },
});
console.log(`Bundled Mermaid ${version} for offline Word export.`);
