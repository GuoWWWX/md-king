 assert.equal(await page.locator('#editor .mk-cm-table').count(),0,'table syntax inside a fenced code block must stay code');
 assert.deepEqual(errors,[]);
 console.log('PASS: quoted and callout tables render, edit without losing quote markers, fold, expose source and support read-only/light/dark.');
