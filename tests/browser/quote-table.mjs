 await page.waitForFunction(()=>!document.querySelector('#editor .mk-cm-table'));
 assert.equal(await page.locator('#editor .mk-cm-callout-toggle').getAttribute('aria-expanded'),'false');
 await page.locator('#editor .mk-cm-callout-toggle').click();
 await page.waitForSelector('#editor .mk-cm-table');
 assert.equal(await cell(1,1).textContent(),'已修改');
 await page.getByRole('button',{name:'编辑 Markdown 源码'}).click();
 assert.equal(await page.locator('#editor .mk-cm-table').count(),0);
 assert.match(await page.evaluate(()=>window.fixture.source),/> \| \*\*粗体\*\* \| 已修改 \|/);
 await page.locator('#outside').click();
 await page.evaluate(()=>{const v=window.fixture.view;v.dispatch({selection:{anchor:v.state.doc.length}})});
 await page.waitForSelector('#editor .mk-cm-table');
