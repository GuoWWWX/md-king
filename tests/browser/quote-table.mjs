 assert.match(source,/> \| \*\*粗体\*\* \| 已修改 \|/);
 assert.match(source,/> \| 公式 \| \$x\^2\$ \|/);
 assert.match(source,/\n\n正文不变$/);
 assert.ok(source.split('\n').filter(line=>line.includes('|')).every(line=>line.startsWith('> ')));
 assert.equal(await page.getByRole('button',{name:'增加表格缩进'}).count(),0);
 assert.equal(await page.getByRole('button',{name:'减少表格缩进'}).count(),0);
