 assert.equal(await cell(1,0).locator('strong').textContent(),'粗体');
 assert.equal(await cell(1,1).locator('code').textContent(),'代码');
 assert.ok(await cell(2,1).locator('.katex').count());
 assert.equal(await page.locator('#editor .mk-cm-block-widget-spacing--table.mk-cm-callout-last').count(),1);
 for(const dark of [true,false]){
  await page.evaluate(dark=>window.fixture.configure({isDark:dark}),dark);
  await page.waitForFunction(dark=>{
   const el=document.querySelector('#editor .mk-cm-block-widget-spacing--table.mk-cm-callout-last');
   if(!el || document.documentElement.classList.contains('dark')!==dark)return false;
   const style=getComputedStyle(el);
   return /0px -1px 0px 0px inset/.test(style.boxShadow) && parseFloat(style.paddingBottom)>=7;
  },dark);
 }
 await cell(1,1).click();await input(1,1).fill('已修改');await finish();
